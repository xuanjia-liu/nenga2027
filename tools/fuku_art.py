#!/usr/bin/env python3
"""Split the ひつじ福笑い sprite sheet (assets/source/fukuwarai.svg, supplied by the user) into the head and the
draggable parts → generated/fuku_art.js (window.NENGA_FUKU).

    python3 tools/fuku_art.py

The sheet is one 1584×993 SVG: the head (wool, face, cheeks, horns) on the left, the parts on the right.
Each element is assigned by the centre of its bounding box; every piece keeps the sheet's coordinates and gets
its own viewBox (its padded bounding box), so a part drawn at its target spot lines up with the head exactly.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / 'assets/source/fukuwarai.svg', ROOT / 'generated/fuku_art.js'

# piece → bounding-box centre window (x0, x1, y0, y1) in sheet units
PIECES = {
    'head':  (200, 1100, 0, 993),
    'eyeL':  (1160, 1260, 220, 340),
    'eyeR':  (1380, 1490, 220, 340),
    'nose':  (1140, 1270, 355, 455),
    'mouth': (1360, 1520, 355, 445),
    'earL':  (1100, 1290, 470, 610),
    'earR':  (1360, 1550, 470, 610),
}
PAD = 6


def path_bbox(d):
    """Bounding box of an absolute-command path (M L C H V Z — what the sheet uses), measured on the curves themselves."""
    xs, ys, cx, cy, sx, sy = [], [], 0.0, 0.0, 0.0, 0.0
    for cmd, args in re.findall(r'([MLCHVZmlchvz])([^MLCHVZmlchvz]*)', d):
        n = [float(v) for v in re.findall(r'-?\d*\.?\d+(?:e-?\d+)?', args)]
        if cmd.islower() and cmd != 'z':
            raise ValueError('relative path commands are not supported: ' + cmd)
        if cmd == 'M': cx, cy = sx, sy = n[0], n[1]; pts = [(cx, cy)] + list(zip(n[2::2], n[3::2])); cx, cy = pts[-1]
        elif cmd == 'L': pts = list(zip(n[0::2], n[1::2])); cx, cy = pts[-1]
        elif cmd == 'H': pts = [(v, cy) for v in n]; cx = n[-1]
        elif cmd == 'V': pts = [(cx, v) for v in n]; cy = n[-1]
        elif cmd == 'C':
            pts = []
            for i in range(0, len(n), 6):
                x1, y1, x2, y2, x3, y3 = n[i:i + 6]
                for k in range(25):
                    t = k / 24; u = 1 - t
                    pts.append((u**3 * cx + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x3, u**3 * cy + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y3))
                cx, cy = x3, y3
        else: pts = []; cx, cy = sx, sy
        xs += [q[0] for q in pts]; ys += [q[1] for q in pts]
    return min(xs), min(ys), max(xs), max(ys)


def main():
    svg = SRC.read_text()
    out = {k: {'els': [], 'bb': [1e9, 1e9, -1e9, -1e9]} for k in PIECES}
    for el in re.findall(r'<(?:path|ellipse)\b[^>]*/>', svg):
        if el.startswith('<path'):
            bb = path_bbox(re.search(r'\bd="([^"]+)"', el).group(1))
        else:
            a = {k: float(re.search(rf'\b{k}="([^"]+)"', el).group(1)) for k in ('cx', 'cy', 'rx', 'ry')}
            r = max(a['rx'], a['ry'])
            bb = (a['cx'] - r, a['cy'] - r, a['cx'] + r, a['cy'] + r)
        cx, cy = (bb[0] + bb[2]) / 2, (bb[1] + bb[3]) / 2
        key = next((k for k, (x0, x1, y0, y1) in PIECES.items() if x0 <= cx <= x1 and y0 <= cy <= y1), None)
        if not key:
            raise SystemExit(f'unassigned element at ({cx:.0f}, {cy:.0f})')
        p = out[key]; p['els'].append(el)
        p['bb'] = [min(p['bb'][0], bb[0]), min(p['bb'][1], bb[1]), max(p['bb'][2], bb[2]), max(p['bb'][3], bb[3])]
    data = {}
    for k, p in out.items():
        x0, y0, x1, y1 = p['bb']
        box = [round(x0 - PAD, 1), round(y0 - PAD, 1), round(x1 - x0 + PAD * 2, 1), round(y1 - y0 + PAD * 2, 1)]
        data[k] = {'box': box, 'svg': ''.join(p['els'])}
        print(f'{k:6s} {len(p["els"]):3d} elements  box {box}')
    OUT.write_text('/* generated by tools/fuku_art.py from assets/source/fukuwarai.svg — do not edit */\n'
                   'window.NENGA_FUKU = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(OUT.relative_to(ROOT), f'{OUT.stat().st_size / 1e3:.1f} kB')


if __name__ == '__main__':
    main()
